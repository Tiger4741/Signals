// ============================================================
// ComplexOps.hpp
//
// Обёртки и дополнения к std::complex<double> для задач ЦОС.
// Ничего «своего» здесь нет: используются стандартные операции
// (+ - * /, std::abs, std::arg, std::conj, std::norm),
// но через именованные функции — чтобы код читался так же,
// как формулы в учебнике: |z|, arg z, z·z*, e^{jθ}.
//
// Пример использования:
//     using namespace dsp;
//     Complex z = fromEuler(PI / 4);          // e^{jπ/4}
//     double  A = magnitude(z);               // 1.0
//     double  phi = phase(z);                 // π/4
//     Complex w = conjMul(z, z);              // |z|²  (вещественное)
//     Complex r = rotate90(z);                // z·j
// ============================================================

namespace dsp {
// ------------------------------------------------------------
// Тип комплексного числа
// ------------------------------------------------------------
// std::complex<double> — стандартный контейнер, совместимый со
// всем научным C++ кодом. Алиас нужен только для читаемости:
// dsp::Complex короче, чем std::complex<double>, и его легко
// заменить в одном месте, если когда-нибудь понадобится
// сменить представление (например, на float или на свой тип).
using Complex = std::complex<double>;

// ------------------------------------------------------------
// Константы
// ------------------------------------------------------------

inline constexpr double PI = 3.14159265358979323846;
inline constexpr double TWO_PI = 2.0 * PI;

//constexpr

// лучше использовать constexpr а не const, потому что:
// 1. Производительность: работа просто исчезает из рантайма
// Если значение посчитано на этапе компиляции, то в готовой программе нет кода, который бы его считал.
// Оно уже вшито в бинарник как готовая константа.

// 3. Ошибки ловятся раньше
// Это, пожалуй, самое ценное. Ошибка на этапе компиляции стоит дешевле, чем ошибка в рантайме.


//inline

//1. Это подсказка компилятору заменить вызов функции(переменной) её непосредственным
// кодом прямо в месте вызова
//2.В C++ есть важнейшее правило: Правило одного определения (ODR). Один и тот же класс или функцию нельзя определять дважды в разных частях программы.
// Представьте, что вы пишете библиотеку для своего Qt-проекта и создали заголовочный файл math_utils.h
// Если этот заголовочный файл math_utils.h подключить через #include в mainwindow.cpp и в database.cpp,
// то компилятор попытается скомпилировать функцию sum два раза. На этапе сборки (линковки) проект упадет с ошибкой: multiple definition of 'sum' (функция определена дважды).
// Слово inline говорит линковщику: «Эта функция будет дублироваться во многих файлах. Это нормально.
// Не ругайся, просто выбери любую одну копию, а остальные проигнорируй»




// Мнимая единица как отдельная константа. В формулах вида
// e^{-jωt} удобнее писать j * omega * t, чем Complex(0, 1).
inline const Complex j{0.0, 1.0};

// ------------------------------------------------------------
// Конструирование
// ------------------------------------------------------------

// Точка на единичной окружности: e^{jθ} = cos θ + j sin θ.
// Это центральный объект всей ЦОС: из него строятся базисные
// функции ДПФ, комплексные несущие, аналитический сигнал.



// Функции, которые создают комплексное число ИЗ (from) заданных полярных координат
// по формуле Эйлера возвращает комплексное число 1 * e^(j·θ)
inline Complex fromEuler(double theta) noexcept{
    return std::polar(1.0, theta);
}

//noexcept

//Ключевое слово noexcept в C++ используется для того,
//чтобы гарантировать компилятору: «эта функция никогда не выбросит исключение (exception)»

// 1. Упрощение кода компилятора (Ускорение работы программы)
// Когда компилятор видит обычную функцию, которая может выбросить исключение,
// он вынужден генерировать кучу скрытого служебного кода.
// Этот код нужен для так называемого «раскручивания стека» (stack unwinding) — чтобы в случае ошибки программа знала,
// в каком порядке уничтожать созданные локальные объекты.


// 2. Что будет, если функция noexcept всё-таки выбросит исключение?
// Вы нарушите контракт, и программа мгновенно завершится аварийно.

// В современном C++ хорошим тоном считается ставить noexcept для:
// • Конструкторов перемещения и move-операторов присваивания (иначе std::vector не будет их использовать).
// • Деструкторов (в C++11 и новее они и так по умолчанию считаются noexcept).
// • Простых функций-геттеров, которые просто возвращают значение переменной




// Комплексное число из полярных координат: r·e^{jθ}.
// Функционально совпадает с std::polar, но живёт в namespace dsp —
// чтобы в формулах не смешивать два стиля записи.

inline Complex fromPolar(double rho, double theta) noexcept {
    return std::polar(rho, theta);
}




// ------------------------------------------------------------
// Свойства: модуль, фаза, энергия
// ------------------------------------------------------------

// |z| = √(re² + im²).

inline double magnitude(const Complex& z) noexcept {
    return std::abs(z);
}
// const Complex& z - принимает число по константной ссылке


}

